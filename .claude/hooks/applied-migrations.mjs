#!/usr/bin/env node
//
// Blocks edits to migrations that already exist on disk.
//
// WHY THIS HOOK OWNS THE RULE OUTRIGHT, WITH NO CI COUNTERPART
//
// Every other rule in this repository is owned by CI, and where a hook exists it is
// a cached mirror of the CI rule for speed - never a second rule. This one is the
// deliberate exception, because it has no CI owner and cannot sensibly have one.
//
// An applied migration must never be edited: databases have already run it, so
// changing it rewrites history and lets environments diverge silently. But a diff
// touching a migration file is perfectly legitimate when the migration is NEW, and
// illegitimate when it is not - and only the local filesystem, at the moment of the
// edit, knows which case it was. By the time CI sees a pull request, both look the
// same. The rule is stated in .claude/skills/add-migration/SKILL.md and until now
// nothing enforced it at all.
//
// Creating a new migration is untouched: `dotnet ef migrations add` writes through
// the CLI, which no tool-level hook observes, and a Write to a path that does not
// yet exist is allowed here anyway.
//
// Fails OPEN. A broken hook must never wedge the editor.
// Escape hatch: APPLIED_MIGRATIONS_BYPASS=1
//

import { existsSync } from "node:fs";
import path from "node:path";

const BYPASS = "APPLIED_MIGRATIONS_BYPASS";

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString("utf8");
}

function resolveTarget(filePath) {
  if (path.isAbsolute(filePath)) return filePath;
  const root = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
  return path.resolve(root, filePath);
}

function isMigrationFile(filePath) {
  if (!filePath.toLowerCase().endsWith(".cs")) return false;
  return filePath.split(/[\/]/).includes("Migrations");
}

if (process.env[BYPASS] === "1") process.exit(0);

let payload;
try {
  payload = JSON.parse(await readStdin());
} catch {
  process.exit(0); // not a hook invocation; never block on our own failure
}

const raw = payload?.tool_input?.file_path ?? payload?.tool_input?.notebook_path;
if (!raw) process.exit(0);
if (!isMigrationFile(raw)) process.exit(0);

const target = resolveTarget(raw);
if (!existsSync(target)) process.exit(0); // a new migration - the normal, allowed case

const reason = [
  `Blocked: ${path.basename(target)} is a migration that already exists.`,
  "",
  "An applied migration is never edited. A database somewhere has already run it, so",
  "changing it rewrites history: the schema a fresh clone builds stops matching the",
  "schema a deployed database actually has, and nothing reports the divergence.",
  "",
  "What to do instead:",
  "  - Change the model, then `dotnet ef migrations add <Name>` to add a NEW migration.",
  "  - If this migration has never been applied anywhere, remove it properly with",
  "    `dotnet ef migrations remove` and regenerate it - do not hand-edit it.",
  "  - The model snapshot is regenerated by the tooling. Do not hand-edit that either.",
  "",
  "See .claude/skills/add-migration/SKILL.md.",
  `Deliberate exception: set ${BYPASS}=1.`,
].join("\n");

process.stdout.write(JSON.stringify({
  hookSpecificOutput: {
    hookEventName: "PreToolUse",
    permissionDecision: "deny",
    permissionDecisionReason: reason,
  },
}));
process.exit(0);
